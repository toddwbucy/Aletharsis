// Package benchmarks_test characterizes stages without changing production APIs.
package benchmarks_test

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strconv"
	"strings"
	"testing"
	"unicode/utf8"

	"github.com/toddwbucy/Aletharsis/internal/analyzers"
	"github.com/toddwbucy/Aletharsis/internal/audit"
	"github.com/toddwbucy/Aletharsis/internal/evidence"
	"github.com/toddwbucy/Aletharsis/internal/parsers"
	"github.com/toddwbucy/Aletharsis/internal/reporters"
)

type corpusCase struct {
	Name, Prefix, Repeat, Suffix string
	Hash                         string `json:"sha256_65536"`
}

var sink any

func corpus(b testing.TB) []corpusCase {
	b.Helper()
	raw, err := os.ReadFile("../../benchmarks/corpus.json")
	if err != nil {
		b.Fatal(err)
	}
	var spec struct{ Cases []corpusCase }
	if err := json.Unmarshal(raw, &spec); err != nil {
		b.Fatal(err)
	}
	seen := map[string]bool{}
	for _, c := range spec.Cases {
		if c.Name == "" || filepath.Base(c.Name) != c.Name || seen[c.Name] || c.Repeat == "" || len(c.Prefix)+len(c.Suffix) > 16 {
			b.Fatal("invalid corpus specification")
		}
		seen[c.Name] = true
	}
	if len(spec.Cases) == 0 {
		b.Fatal("empty corpus")
	}
	return spec.Cases
}
func sizes(b *testing.B) []int {
	b.Helper()
	value := os.Getenv("ALETHARSIS_BENCH_SIZES")
	if value == "" {
		value = "65536"
	}
	var result []int
	for _, s := range strings.Split(value, ",") {
		n, err := strconv.Atoi(s)
		if err != nil || n < 16 || n > audit.MaxBytes {
			b.Fatalf("invalid benchmark size %q", s)
		}
		result = append(result, n)
	}
	return result
}
func input(c corpusCase, n int) []byte {
	remaining := n - len(c.Prefix) - len(c.Suffix)
	data := append([]byte(c.Prefix), bytes.Repeat([]byte(c.Repeat), remaining/len(c.Repeat))...)
	data = append(data, bytes.Repeat([]byte{' '}, remaining%len(c.Repeat))...)
	return append(data, []byte(c.Suffix)...)
}
func analyze(d *evidence.Document) []evidence.Finding {
	var fs []evidence.Finding
	for _, a := range []analyzers.Analyzer{analyzers.Unicode{}, analyzers.Emoji{}, analyzers.Text{}, analyzers.Patterns{}, analyzers.Identifiers{}, analyzers.Metadata{}} {
		fs = append(fs, a.Analyze(d)...)
	}
	return fs
}
func BenchmarkStages(b *testing.B) {
	if runtime.GOOS != "linux" {
		b.Skip("full snapshot stage requires Linux")
	}
	for _, c := range corpus(b) {
		for _, n := range sizes(b) {
			data := input(c, n)
			path := filepath.Join(b.TempDir(), c.Name+".txt")
			if err := os.WriteFile(path, data, 0600); err != nil {
				b.Fatal(err)
			}
			name := fmt.Sprintf("%s/%d", c.Name, n)
			b.Run(name+"/parse", func(b *testing.B) {
				b.ReportAllocs()
				b.SetBytes(int64(n))
				for i := 0; i < b.N; i++ {
					d, err := (parsers.TextParser{}).Parse(data)
					if err != nil {
						b.Fatal(err)
					}
					sink = d
				}
			})
			b.Run(name+"/analyze", func(b *testing.B) {
				b.ReportAllocs()
				b.SetBytes(int64(n))
				for i := 0; i < b.N; i++ {
					b.StopTimer()
					d, err := (parsers.TextParser{}).Parse(data)
					if err != nil {
						b.Fatal(err)
					}
					b.StartTimer()
					sink = analyze(&d)
				}
			})
			b.Run(name+"/serialize", func(b *testing.B) {
				b.StopTimer()
				report := audit.Run(path)
				if report.Status != "completed" {
					b.Fatal("fixture audit failed")
				}
				b.ReportAllocs()
				b.SetBytes(int64(n))
				b.StartTimer()
				for i := 0; i < b.N; i++ {
					rendered, err := reporters.JSON(report, true)
					if err != nil {
						b.Fatal(err)
					}
					b.ReportMetric(float64(len(rendered)), "report_bytes/op")
					sink = rendered
				}
			})
			b.Run(name+"/audit", func(b *testing.B) {
				b.ReportAllocs()
				b.SetBytes(int64(n))
				for i := 0; i < b.N; i++ {
					r := audit.Run(path)
					if r.Status != "completed" {
						b.Fatal("fixture audit failed")
					}
					sink = r
				}
			})
		}
	}
}

// These hashes were generated by the executable harness's Python generator.
// Keep both stage and process measurements on identical UTF-8 input bytes.
func TestCorpusIdentity(t *testing.T) {
	for _, c := range corpus(t) {
		t.Run(c.Name, func(t *testing.T) {
			for _, n := range []int{16, 65536, 1048576, audit.MaxBytes} {
				data := input(c, n)
				if len(data) != n || !utf8.Valid(data) {
					t.Fatal("invalid corpus byte length or UTF-8")
				}
				if n == 65536 && fmt.Sprintf("%x", sha256.Sum256(data)) != c.Hash {
					t.Fatal("corpus hash differs from process harness")
				}
			}
		})
	}
}
